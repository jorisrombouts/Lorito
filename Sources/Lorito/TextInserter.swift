import AppKit
import Carbon.HIToolbox

/// Puts text on the pasteboard, sends ⌘V to the frontmost app, restores the previous clipboard.
@MainActor
enum TextInserter {
    /// How long the target app gets to read the paste before the old clipboard comes back. Reading is not observable.
    static let restoreDelay = 0.6
    /// nspasteboard.org markers: clipboard managers skip the dictation instead of recording it.
    static let markerTypes = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                              NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]

    /// nil when ⌘V was posted, else why it could not be. Whether the app accepted the paste is not observable.
    static func insert(_ text: String) -> String? {
        // A password field turns on Secure Event Input; a dictation never goes there, nor onto the clipboard.
        if IsSecureEventInputEnabled() { NSLog("insert: refused, secure input on"); return "Secure input is on, not pasted" }
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        pb.clearContents()
        let wrote = pb.setString(text, forType: .string)
        markerTypes.forEach { pb.setData(Data(), forType: $0) }
        let ours = pb.changeCount
        let trusted = AXIsProcessTrusted(), canPost = CGPreflightPostEventAccess()
        NSLog("insert: ax_trusted=%d post_event_ok=%d pasteboard_wrote=%d chars=%d front=%@",
              trusted ? 1 : 0, canPost ? 1 : 0, wrote ? 1 : 0, text.count,
              NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "?")

        // Every item and type comes back (images, files, rich text), unless something was copied in the meantime.
        defer {
            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
                guard pb.changeCount == ours else { return }
                restore(saved, to: pb)
            }
        }

        guard trusted, canPost else { return "Accessibility permission missing" }
        guard wrote else { return "Clipboard is not writable" }
        let src = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        else { return "Could not send ⌘V" }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return nil
    }

    /// The clipboard as data per item and type; promised types that never resolve are left out.
    static func snapshot(_ pb: NSPasteboard) -> [[(NSPasteboard.PasteboardType, Data)]] {
        (pb.pasteboardItems ?? []).map { item in item.types.compactMap { t in item.data(forType: t).map { (t, $0) } } }
    }

    static func restore(_ items: [[(NSPasteboard.PasteboardType, Data)]], to pb: NSPasteboard) {
        pb.clearContents()
        let restored = items.filter { !$0.isEmpty }.map { pairs in
            let item = NSPasteboardItem()
            pairs.forEach { item.setData($0.1, forType: $0.0) }
            return item
        }
        if !restored.isEmpty { pb.writeObjects(restored) }
    }
}
